# 7. Reusable violin plot function
# ============================================================

make_violin <- function(
  data,
  p_label,
  panel_label
) {

  # Generate labels with sample sizes

  counts <- data %>%
    count(Category)

  x_labels <- setNames(
    paste0(
      counts$Category,
      "\n(n = ",
      counts$n,
      ")"
    ),
    counts$Category
  )

  ggplot(
    data,
    aes(
      x = Category,
      y = Enrichment,
      fill = Category
    )
  ) +

    # Violin plot
    geom_violin(
      trim = FALSE,
      alpha = 0.25,
      width = 0.8,
      colour = NA
    ) +

    # Individual peaks
    geom_jitter(
      aes(colour = Category),
      width = 0.12,
      size = 0.65,
      alpha = 0.25
    ) +

    # Embedded box plot
    geom_boxplot(
      width = 0.20,
      outlier.shape = NA,
      alpha = 0.7,
      colour = "black",
      linewidth = 0.5
    ) +

    scale_fill_manual(
      values = colors
    ) +

    scale_colour_manual(
      values = colors
    ) +

    scale_x_discrete(
      labels = x_labels
    ) +

    # Statistical comparison bracket
    annotate(
      "segment",
      x = 1,
      xend = 2,
      y = y_bracket,
      yend = y_bracket,
      linewidth = 0.4
    ) +

    annotate(
      "segment",
      x = 1,
      xend = 1,
      y = y_bracket - 0.08,
      yend = y_bracket,
      linewidth = 0.4
    ) +

    annotate(
      "segment",
      x = 2,
      xend = 2,
      y = y_bracket - 0.08,
      yend = y_bracket,
      linewidth = 0.4
    ) +

    annotate(
      "text",
      x = 1.5,
      y = y_text,
      label = p_label,
      size = 3.5
    ) +

    coord_cartesian(
      ylim = c(0, y_limit)
    ) +

    labs(
      x = NULL,
      y = "Mean ChIP/input ratio per IDR peak",
      tag = panel_label
    ) +

    plot_theme +

    theme(
      plot.tag = element_text(
        face = "bold",
        size = 15
      ),

      plot.tag.position = c(
        0.02, 0.98
      )
    )
}

