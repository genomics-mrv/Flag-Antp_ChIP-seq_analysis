# Read the TSV files generated by multiBigwigSummary.
# The final column contains the mean bigWig signal per BED interval.

read_enrichment <- function(file, category) {

  if (!file.exists(file)) {
    stop("Missing input file: ", file)
  }

  data <- read.delim(
    file,
    header = TRUE,
    check.names = FALSE
  )

  data.frame(
    Enrichment = as.numeric(data[[ncol(data)]]),
    Category = category
  )
}

# Panel A: Motif status

motif <- read_enrichment(
  file.path(INPUT_DIR, "Motif_Containing_enrichment.tsv"),
  "Motif-containing"
)

motif_free <- read_enrichment(
  file.path(INPUT_DIR, "Motif_Free_enrichment.tsv"),
  "Motif-free"
)

df_motif <- bind_rows(
  motif,
  motif_free
)

df_motif$Category <- factor(
  df_motif$Category,
  levels = c(
    "Motif-containing",
    "Motif-free"
  )
)

# Panel B: Shared versus non-shared peaks

shared <- read_enrichment(
  file.path(INPUT_DIR, "Shared_enrichment.tsv"),
  "Shared"
)

unique <- read_enrichment(
  file.path(INPUT_DIR, "Unique_enrichment.tsv"),
  "Non-shared"
)

df_shared <- bind_rows(
  shared,
  unique
)

df_shared$Category <- factor(
  df_shared$Category,
  levels = c(
    "Shared",
    "Non-shared"
  )
)

# Remove missing or non-finite values

df_motif <- df_motif %>%
  filter(is.finite(Enrichment))

df_shared <- df_shared %>%
  filter(is.finite(Enrichment))

# 4. Descriptive statistics
# ============================================================

calculate_stats <- function(data) {

  data %>%
    group_by(Category) %>%
    summarise(
      N = n(),
      Mean = mean(Enrichment),
      SD = sd(Enrichment),
      Median = median(Enrichment),
      Q1 = quantile(Enrichment, 0.25),
      Q3 = quantile(Enrichment, 0.75),
      Min = min(Enrichment),
      Max = max(Enrichment),
      .groups = "drop"
    )
}

stats_motif <- calculate_stats(df_motif)
stats_shared <- calculate_stats(df_shared)

print(stats_motif)
print(stats_shared)

write.csv(
  stats_motif,
  file.path(
    OUTPUT_DIR,
    "FlagAntp_motif_statistics.csv"
  ),
  row.names = FALSE
)

write.csv(
  stats_shared,
  file.path(
    OUTPUT_DIR,
    "FlagAntp_shared_statistics.csv"
  ),
  row.names = FALSE
)

# 5. Statistical tests
# ============================================================

# Two-sided Mann-Whitney U tests

test_motif <- wilcox.test(
  Enrichment ~ Category,
  data = df_motif,
  alternative = "two.sided",
  exact = FALSE,
  correct = FALSE
)

test_shared <- wilcox.test(
  Enrichment ~ Category,
  data = df_shared,
  alternative = "two.sided",
  exact = FALSE,
  correct = FALSE
)

print(test_motif)
print(test_shared)

# Format p-values for figure annotations

format_p <- function(p) {

  if (p < 0.0001) {
    return("p < 0.0001")
  }

  paste0(
    "p = ",
    sprintf("%.3f", p)
  )
}

p_motif <- format_p(test_motif$p.value)
p_shared <- format_p(test_shared$p.value)

# Save statistical results

capture.output(
  cat("Motif-containing versus motif-free peaks\n"),
  print(test_motif),
  cat("\nShared versus non-shared peaks\n"),
  print(test_shared),
  file = file.path(
    OUTPUT_DIR,
    "FlagAntp_statistical_tests.txt"
  )
)

